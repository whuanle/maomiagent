const dictionaries: Record<LanguageCode, Record<TasksI18nKey, string>> = {
  "zh-CN": zhCNMessages,
  "en-US": enUSMessages,
};

export function createTasksTranslator(language: LanguageCode): TasksTranslate {
  const dictionary = dictionaries[language] ?? dictionaries["zh-CN"];

  return (key, params) => {
    const template = dictionary[key] ?? dictionaries["zh-CN"][key] ?? key;
    if (!params) {
      return template;
    }

    return Object.entries(params).reduce((message, [name, value]) => {
      return message.replaceAll(`{${name}}`, String(value));
    }, template);
  };
}