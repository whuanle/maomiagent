const dictionaries: Record<LanguageCode, Record<AgentsI18nKey, string>> = {
  "zh-CN": zhCNMessages,
  "en-US": enUSMessages,
}

export function createAgentsTranslator(language: LanguageCode): AgentsTranslate {
  const dictionary = dictionaries[language] ?? dictionaries["zh-CN"]

  return (key, params) => {
    const template = dictionary[key] ?? dictionaries["zh-CN"][key] ?? key
    if (!params) {
      return template
    }

    return template.replace(/\{([^}]+)\}/g, (token, paramKey: string) => {
      if (!(paramKey in params)) {
        return token
      }
      return String(params[paramKey])
    })
  }
}

